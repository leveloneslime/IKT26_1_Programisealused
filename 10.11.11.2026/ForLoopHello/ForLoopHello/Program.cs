namespace ForLoopHello
{
    internal class Program
    {
        static void Main(string[] args)
        {
            //konsooli rakkendus kus kasutad for loopi
            //kolm korda n'idataks tere tulemast ja lõpus rea number

            int b = 3;
            for (int a = 0; a < b; a++)
            {
                Console.WriteLine("tere tulemast! " + a);

            }
        }
    }
}
